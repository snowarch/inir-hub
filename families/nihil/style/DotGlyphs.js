function iconFor(code, night) {
    var c = String(code)
    if (["113"].indexOf(c) >= 0) return night ? "moon" : "sun"
    if (["116", "119", "122"].indexOf(c) >= 0) return "cloud"
    if (["143", "248", "260"].indexOf(c) >= 0) return "fog"
    if (["200", "386", "389", "392", "395"].indexOf(c) >= 0) return "storm"
    if (["179", "182", "185", "227", "230", "320", "323", "326", "329", "332", "335", "338", "350", "362", "365", "368", "371", "374", "377"].indexOf(c) >= 0) return "snow"
    return "rain"
}
function iconCells(name) {
    var g = icons[name] || icons["sun"]
    var cells = []
    for (var r = 0; r < g.length; ++r)
        for (var c = 0; c < g[r].length; ++c)
            if (g[r][c] === "#") cells.push({ x: c, y: r })
    return { cells: cells, width: 9, height: 9 }
}

function glyph(ch) {
    var key = String(ch).toUpperCase()
    return rows[key] !== undefined ? rows[key] : rows["?"]
}

// The lit cells of a whole line: [{ x, y }] in dot units, with its width and the 7-row height.
function layout(text, tracking) {
    var cells = []
    var x = 0
    var gap = tracking === undefined ? 1 : tracking
    var chars = String(text)
    for (var i = 0; i < chars.length; ++i) {
        var g = glyph(chars[i])
        var w = g[0].length
        for (var r = 0; r < g.length; ++r)
            for (var c = 0; c < w; ++c)
                if (g[r][c] === "#")
                    cells.push({ x: x + c, y: r })
        x += w + (i < chars.length - 1 ? gap : 0)
    }
    return { cells: cells, width: x, height: 7 }
}
